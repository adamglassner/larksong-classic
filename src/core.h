/*
 * Larksong Classic: an alarm clock for every 32-bit Windows from 95 to 11.
 *
 * Rules that keep it running on Windows 95:
 *  - no C runtime (only KERNEL32, USER32, GDI32, WINMM, SHELL32, ADVAPI32, COMDLG32, COMCTL32);
 *  - ANSI ("A") functions only, and only ones that exist in Windows 95;
 *  - no floating point; trigonometry comes from small tables;
 *  - anything newer (WinHTTP for weather and updates) is loaded at run time, only on Windows 7+.
 */
#ifndef LARKSONG_CORE_H
#define LARKSONG_CORE_H

#define WIN32_LEAN_AND_MEAN
#undef WINVER
#undef _WIN32_WINNT
#undef _WIN32_IE
#define WINVER 0x0400
#define _WIN32_WINNT 0x0400
#define _WIN32_IE 0x0300
#include <windows.h>
#include <mmsystem.h>
#include <shellapi.h>
#include <commdlg.h>
#include <commctrl.h>
#include "resource.h"

#include "version.h" /* generated by build.sh from VERSION */

#define APP_NAME   "Larksong Classic"
#define MAX_ALARMS 32
#define MAX_ZONES  6
#define MAX_LAPS   99

/* Themes */
enum { TH_CLASSIC, TH_DARK, TH_TERMINAL, TH_RADIO, TH_RETRO, TH_LARKSONG, TH_DAWN, TH_DUSK, TH_COUNT };

typedef struct {
    int used;
    int hour, minute;
    int days;          /* bit 0 = Sunday ... bit 6 = Saturday; 0 = once */
    int enabled;
    int snooze;        /* minutes */
    int gradual;
    int ramp;          /* seconds */
    char label[48];
    char sound[MAX_PATH]; /* WAV file, or empty for the built-in tone */
    int skipUntil;     /* local minute stamp of a ring dismissed ahead of time; 0 = none */
} Alarm;

typedef struct {
    int theme;
    int use24, showSec, celsius;
    int bedOn, bedH, bedM, wakeH, wakeM, remind, bedDays, bedLink, bedAlarm;
    int zones[MAX_ZONES];
    int zoneCount;
    char city[64];
    int latE4, lonE4;  /* weather location, degrees x 10000 */
    int haveLoc;
    char timerSound[MAX_PATH];
    int trayHint;
} Settings;

typedef struct { const char *name; int offset; int rule; } City;
enum { DST_NONE, DST_US, DST_EU, DST_AU, DST_NZ };

extern HINSTANCE g_inst;
extern Settings S;
extern Alarm A[MAX_ALARMS];
extern const City CITIES[];
extern const int CITY_COUNT;
extern const short SIN60[60];

/* tiny libc replacements */
void *memset(void *d, int c, size_t n);
void *memcpy(void *d, const void *s, size_t n);
int str_len(const char *s);
void str_copy(char *d, const char *s, int n);
void str_cat(char *d, const char *s, int n);
int str_starts(const char *s, const char *prefix);
const char *str_find(const char *hay, const char *needle);
int parse_int(const char *s);
int parse_fixed(const char *s, int scale);   /* "12.345" with scale 100 -> 1235 */
int version_compare(const char *a, const char *b);

/* time */
int days_from_civil(int y, int m, int d);
void civil_from_days(int z, int *y, int *m, int *d);
int weekday_from_days(int days); /* 0 = Sunday */
int local_stamp(void);            /* minutes since 1970 in local time */
int utc_stamp(void);
void zone_time(int city, int *hour, int *minute, int *dayDelta);
void format_time(char *out, int hour, int minute, int use24);
void format_hm(char *out, int hour, int minute, int use24); /* without AM/PM */
void days_text(char *out, int days);

/* storage */
void store_init(void);
void store_load(void);
void store_save(void);
int  alarm_new(void);

/* platform */
int os_major(void);
int os_minor(void);
int os_is_nt(void);
int os_at_least_win7(void);
void os_name(char *out);
int file_exists(const char *path);
void autostart_set(int on);
int  autostart_get(void);

#endif
